/**
 * 울진군 리 → 읍면 — 기존 정비계획(보고서 4장) 시설명의 리를 법정동 코드(4793)로 맞춘 것.
 * 구산리는 근남면·기성면에 모두 있어 넣지 않았다(읍면 확인 필요).
 */
const RI_BY_EMD: Record<string, string[]> = {
  근남면: ['노음리', '수곡리', '수산리', '진복리', '행곡리'],
  금강송면: ['삼근리', '소광리', '쌍전리', '왕피리', '전곡리'],
  기성면: ['다천리', '방율리', '봉산리', '삼산리', '이평리', '황보리'],
  매화면: ['금매리', '기양리', '매화리', '오산리'],
  북면: ['검성리', '고목리', '나곡리', '덕구리', '두천리', '부구리', '사계리', '상당리', '소곡리', '신화리', '주인리', '하당리'],
  온정면: ['광품리', '덕산리', '덕인리', '선구리', '소태리', '온정리', '외선미리', '조금리'],
  울진읍: ['고성리', '명도리', '신림리', '연지리', '온양리', '읍남리', '정림리', '호월리'],
  죽변면: ['봉평리', '화성리', '후정리'],
  평해읍: ['삼달리', '오곡리', '월송리', '직산리', '평해리', '학곡리'],
  후포면: ['삼율리'],
}

const EMD_BY_RI = new Map(Object.entries(RI_BY_EMD).flatMap(([emd, ris]) => ris.map((ri) => [ri, emd] as const)))

/** 리명(«구산리1»처럼 뒤 숫자는 뗌)으로 읍면 찾기 — 모르면 '' */
export function smallPublicEmdOfRi(ri: string): string {
  return EMD_BY_RI.get(ri.replace(/\d+$/, '')) ?? ''
}
