package component.landInfo.service;

public class LandInfoCodeVO{
	private String code_name;
	private String code_kor_name;
	private String code_number;
	private String number_kor_name;
	
	private String to_code;
	public String getCode_name() {
		return code_name;
	}
	public void setCode_name(String code_name) {
		this.code_name = code_name;
	}
	public String getCode_kor_name() {
		return code_kor_name;
	}
	public void setCode_kor_name(String code_kor_name) {
		this.code_kor_name = code_kor_name;
	}
	public String getCode_number() {
		return code_number;
	}
	public void setCode_number(String code_number) {
		this.code_number = code_number;
	}
	public String getNumber_kor_name() {
		return number_kor_name;
	}
	public void setNumber_kor_name(String number_kor_name) {
		this.number_kor_name = number_kor_name;
	}
	public String getTo_code() {
		return to_code;
	}
	public void setTo_code(String to_code) {
		this.to_code = to_code;
	}
}
